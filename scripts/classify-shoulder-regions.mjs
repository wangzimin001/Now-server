import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V9__add_shoulder_regions.sql')

// 这些动作的轨迹主要是爆发、旋转袖训练或静态稳定，单凭当前资料无法可靠分到三角肌前中后束。
// 保留为空比强行贴标签更专业；它们仍显示在“肩部/全部”中。
const UNKNOWN_IDS = new Set([
  '0067', '0100', '0128', '0216', '0235', '0543', '0552',
  '0863', '0864', '2271', '3548', '3641'
])

export function classifyShoulderRegions(exercise) {
  const id = String(exercise.id || '').padStart(4, '0')
  const name = String(exercise.name || '').toLowerCase()
  if (UNKNOWN_IDS.has(id)) return []

  // 反向飞鸟、后束划船和俯身侧平举均以肩水平外展为主，归入后束。
  if (name.includes('reverse fly') || name.includes('revers fly') || name.includes('rear delt')
    || name.includes('rear lateral') || name.includes('rear fly') || name.includes('deltoid rear')) {
    return ['后束']
  }

  // 同时包含前举和侧举轨迹的动作允许双标签，避免丢失复合轨迹信息。
  if (name.includes('front lateral') || name.includes('lateral to front') || name.includes('around world')
    || name.includes('round arm') || name === 'dumbbell raise' || name.includes('standing alternate raise')) {
    return ['前束', '中束']
  }

  // 侧平举、直立划船、Y/T 举和古巴推举以肩外展为核心，优先标记中束。
  if (name.includes('lateral raise') || name.includes('upright row') || name.includes('y-raise')
    || name.includes('t-raise') || name.includes('full can') || name.includes('iron cross')
    || name.includes('cuban press') || name.includes('side lying one hand raise')) {
    return ['中束']
  }

  // 各类前平举和上斜举主要发生肩屈，归入前束。
  if (name.includes('front raise') || name.includes('forward raise') || name.includes('front shoulder raise')
    || name.includes('incline raise')) {
    return ['前束']
  }

  // 过顶推、军推、推举及挺举同时大量使用前束和中束，因此保留双标签。
  if (name.includes('press') || name.includes('jerk') || name.includes('snatch')
    || name.includes('thruster') || name.includes('bradford')) {
    return ['前束', '中束']
  }

  // 数据集剩余可判断动作是后束拉伸，归入其明确目标区域。
  if (name.includes('rear deltoid stretch')) return ['后束']
  return []
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'shoulders')
const classified = exercises.map(exercise => ({ exercise, regions: classifyShoulderRegions(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length > 0).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

// 迁移显式记录来源动作 ID，保证分类结果不受数据集排序变化影响。
const migration = `-- Shoulder-region classification generated by scripts/classify-shoulder-regions.mjs.
-- Primary category remains shoulders; each reliable exercise receives one or two Chinese secondary regions.

ALTER TABLE exercise
    ADD COLUMN shoulder_regions JSON NULL AFTER back_regions;

UPDATE exercise
SET shoulder_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'shoulders';
`

fs.writeFileSync(migrationFile, migration)
console.log(`肩部动作：${exercises.length}；已分类：${exercises.length - unknown.length}；待确认：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
