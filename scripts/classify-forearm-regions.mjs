import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V14__add_forearm_regions_and_rename_arm_categories.sql')

export function classifyForearmRegions(exercise) {
  const name = String(exercise.name || '').toLowerCase()
  if (name.includes('pronation') || name.includes('supination') || name.includes('rotate')
    || name.includes('wrist circles')) return ['旋前旋后']
  if (name.includes('finger curl') || name.includes('gripper') || name.includes('hand squeeze')
    || name.includes('hang clean')) return ['握力']
  if (name.includes('wrist roller')) return ['腕屈肌', '腕伸肌']
  if (name.includes('reverse wrist') || name.includes('revers wrist') || name.includes('palms down')) return ['腕伸肌']
  if (name.includes('wrist curl') || name.includes('palms up') || name.includes('back wrist')) return ['腕屈肌']
  // 前臂支撑动作与腕部拉伸缺少明确屈伸方向，不强行归类。
  return []
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'lower arms')
const classified = exercises.map(exercise => ({ exercise, regions: classifyForearmRegions(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length > 0).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

const migration = `-- Forearm classification and Chinese category naming generated by scripts/classify-forearm-regions.mjs.
ALTER TABLE exercise
    ADD COLUMN forearm_regions JSON NULL AFTER calf_regions;

UPDATE exercise
SET forearm_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'lower arms';

UPDATE exercise SET category_name = '大臂' WHERE category_code = 'upper arms';
UPDATE exercise SET category_name = '小臂' WHERE category_code = 'lower arms';
`

fs.writeFileSync(migrationFile, migration)
console.log(`小臂动作：${exercises.length}；已分类：${exercises.length - unknown.length}；仅全部：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}`))
