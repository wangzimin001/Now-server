import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V13__add_calf_regions.sql')

export function classifyCalfRegions(exercise) {
  const name = String(exercise.name || '').toLowerCase()

  // 踝环绕、单腿落地稳定和腓骨肌/胫后肌活动不属于单纯提踵，归入踝部稳定。
  if (name.includes('ankle circles') || name.includes('stabilization') || name.includes('circles knee')
    || name.includes('peroneals') || name.includes('posterior tibialis')) return ['踝部稳定']

  // 反向提踵和脚尖抬起是足背屈动作，以胫骨前肌为主。
  if (name.includes('reverse calf') || name.includes('toe raise')) return ['胫骨前肌']

  // 屈膝坐姿显著削弱腓肠肌贡献，更偏比目鱼肌。
  if (name.includes('seated') || name.includes('seated squat')) return ['比目鱼肌']

  // 站姿、驴式和直膝器械提踵以腓肠肌为主要侧重。
  if (name.includes('standing') || name.includes('donkey') || name.includes('hack')
    || name.includes('floor calf') || name.includes('angled calf')) return ['腓肠肌']

  // 未说明膝角度的提踵、腿举提踵和拉伸无法可靠孤立两者，保留双标签。
  return ['腓肠肌', '比目鱼肌']
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'lower legs')
const classified = exercises.map(exercise => ({ exercise, regions: classifyCalfRegions(exercise) }))
const cases = classified.map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

const migration = `-- Calf classification generated by scripts/classify-calf-regions.mjs.
ALTER TABLE exercise
    ADD COLUMN calf_regions JSON NULL AFTER upper_arm_regions;

UPDATE exercise
SET calf_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'lower legs';
`

fs.writeFileSync(migrationFile, migration)
console.log(`小腿动作：${exercises.length}；已分类：${classified.length}`)
