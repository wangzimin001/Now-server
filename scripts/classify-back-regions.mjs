import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V8__add_back_regions.sql')

function classify(exercise) {
  const name = exercise.name.toLowerCase()
  const secondary = new Set(exercise.secondary_muscles || [])

  // 竖脊肌目标动作统一归入下背部；髋伸肌参与不改变动作库的主要背部用途。
  if (exercise.target === 'spine') return ['下背部']

  // 耸肩主要归斜方肌；肩胛下沉/上提且同时标注菱形肌时兼归上背部。
  if (exercise.target === 'traps') {
    return secondary.has('rhomboids') || name.includes('scapular') || name.includes('scapula')
      ? ['斜方肌', '上背部']
      : ['斜方肌']
  }

  // 划船以肩胛后缩塑造上背厚度，同时普遍包含肩伸，因此允许兼归背阔肌。
  if (exercise.target === 'upper back') {
    const alsoLats = name.includes('row') || name.includes('pull-up') || name.includes('pull up') || name.includes('lever')
    return alsoLats ? ['上背部', '背阔肌'] : ['上背部']
  }

  // 垂直拉与上拉主要塑造背阔宽度；源数据明确包含菱形肌/后束时补充上背标签。
  if (exercise.target === 'lats') {
    const alsoUpperBack = secondary.has('rhomboids') || secondary.has('rear deltoids') || name.includes('muscle up')
    return alsoUpperBack ? ['背阔肌', '上背部'] : ['背阔肌']
  }

  return []
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'back')
const classified = exercises.map(exercise => ({ exercise, regions: classify(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

const migration = `-- Back-region classification generated by scripts/classify-back-regions.mjs.
-- Primary category remains back; each exercise receives one or two bodybuilding-oriented regions.

ALTER TABLE exercise
    ADD COLUMN back_regions JSON NULL AFTER chest_regions;

UPDATE exercise
SET back_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'back';
`

fs.writeFileSync(migrationFile, migration)
console.log(`背部动作：${exercises.length}；已分类：${exercises.length - unknown.length}；待确认：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
