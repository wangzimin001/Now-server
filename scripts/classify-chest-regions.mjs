import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V7__add_chest_regions.sql')

// 这些条目虽然被源数据放在胸部，但目标肌或动作轨迹不足以判断胸大肌区域。
// 保留空分类比猜测更安全；前端“胸部/全部”仍会展示，二级筛选不会误导用户。
const UNKNOWN_IDS = new Set([
  '0050', '0191', '0328', '0500', '0759',
  '2139', '2203', '2209', '3011', '3021'
])

function classify(exercise) {
  const name = exercise.name.toLowerCase()
  if (UNKNOWN_IDS.has(exercise.id)) return []

  // 反握平板和颈前卧推兼有锁骨部与水平内收特征，允许两个标签表达实际侧重。
  if (name.includes('guillotine') || (name.includes('reverse grip') && !name.includes('incline') && !name.includes('decline'))) {
    return ['上胸', '中胸']
  }
  // 俯卧撑的 incline/decline 描述的是手或脚的位置，与卧推凳角度的侧重方向相反。
  if (name.includes('decline push-up') || name.includes('decline push up')) return ['上胸']
  if (name.includes('incline push-up') || name.includes('incline push up')) return ['下胸']

  // 低位绳索向上夹合偏上胸；名称直接声明 upper chest 的动作同样归入上胸。
  if (name.includes('cable low fly') || name.includes('upper chest')) return ['上胸']
  if (name.includes('incline')) return ['上胸']

  // 下斜推/飞鸟、双杠臂屈伸和上拉的力线更偏胸肋部下侧。
  if (name.includes('decline') || name.includes('dip') || name.includes('pullover')) return ['下胸']

  // 印度式、折刀式和俄式挺身俯卧撑跨越水平与斜上推阶段，用双标签保留其复合轨迹。
  if (name.includes('hindu') || name.includes('pike push up') || name.includes('planche push-up')) {
    return ['上胸', '中胸']
  }

  // 其余平板推、水平夹胸、常规俯卧撑、胸部拉伸及胸前投掷统一作为中胸侧重。
  return ['中胸']
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'chest')
const classified = exercises.map(exercise => ({ exercise, regions: classify(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const assigned = classified.filter(item => item.regions.length > 0)

// 迁移显式写入来源动作 ID，避免以后数据集顺序变化导致同一迁移产生不同结果。
const cases = assigned.map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

const migration = `-- Chest-region classification generated by scripts/classify-chest-regions.mjs.
-- Primary category remains chest; each reliable exercise receives one or two Chinese secondary regions.

ALTER TABLE exercise
    ADD COLUMN chest_regions JSON NULL AFTER category_name;

UPDATE exercise
SET chest_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'chest';
`

fs.writeFileSync(migrationFile, migration)
console.log(`胸部动作：${exercises.length}；已分类：${assigned.length}；待确认：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
