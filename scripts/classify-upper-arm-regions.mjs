import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V12__add_upper_arm_regions.sql')

export function classifyUpperArmRegions(exercise) {
  const name = String(exercise.name || '').toLowerCase()
  if (exercise.target === 'triceps') return ['三头']
  if (exercise.target !== 'biceps') return []

  // 锤式、反握、佐特曼和腕屈伸主要强调肱肌/肱桡肌，不强行解释为二头长短头侧重。
  const isBrachialisDominant = name.includes('hammer') || name.includes('reverse') || name.includes('revers ')
    || name.includes('zottman') || name.includes('neutral wrist') || name.includes('clean')
    || name.includes('pulldown (with rope)')
  if (isBrachialisDominant) return []

  // 宽握、牧师凳、集中、蜘蛛和高位弯举让上臂位于身体前方或外展，更偏短头（内侧）。
  const innerBias = name.includes('wide grip') || name.includes('wide-grip') || name.includes('preacher')
    || name.includes('concentration') || name.includes('spider') || name.includes('inner biceps')
    || name.includes('high curl') || name.includes('overhead curl') || name.includes('arm blaster')
  if (innerBias) return ['二头内侧']

  // 窄握、上斜、拖拽和上臂位于躯干后方的弯举更偏长头（外侧）。
  const outerBias = name.includes('close grip') || name.includes('close-grip') || name.includes('narrow pull')
    || name.includes('incline') || name.includes('drag curl') || name.includes('lying supine')
    || name.includes('prone curl')
  if (outerBias) return ['二头外侧']

  // 常规正握弯举无法可靠孤立长短头，用双标签表达二者共同参与。
  return ['二头内侧', '二头外侧']
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'upper arms')
const classified = exercises.map(exercise => ({ exercise, regions: classifyUpperArmRegions(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length > 0).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

// 内侧/外侧是训练侧重标签，迁移按来源动作 ID 固化审计结果。
const migration = `-- Upper-arm classification generated by scripts/classify-upper-arm-regions.mjs.
-- Inner/outer biceps are short/long-head training-emphasis labels.

ALTER TABLE exercise
    ADD COLUMN upper_arm_regions JSON NULL AFTER waist_regions;

UPDATE exercise
SET upper_arm_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'upper arms';
`

fs.writeFileSync(migrationFile, migration)
console.log(`上臂动作：${exercises.length}；已分类：${exercises.length - unknown.length}；仅全部：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
