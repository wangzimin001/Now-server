import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V11__add_waist_regions.sql')

// 这些条目实际是股直肌拉伸、全身活动或冲刺，现有资料不足以归入腰腹训练区域。
const UNKNOWN_IDS = new Set(['1714', '1687', '3119', '0858'])

export function classifyWaistRegions(exercise) {
  const id = String(exercise.id || '').padStart(4, '0')
  const name = String(exercise.name || '').toLowerCase()
  if (UNKNOWN_IDS.has(id)) return []

  const isOblique = name.includes('twist') || name.includes('side') || name.includes('oblique')
    || name.includes('russian') || name.includes('windmill') || name.includes('cross body')
    || name.includes('bicycle') || name.includes('heel toucher') || name.includes('elbow-to-knee')
    || name.includes('judo flip') || name.includes('figure 8') || name.includes('landmine 180')
    || name.includes('spell caster') || name.includes('sledge hammer') || name.includes('one arm slam')

  // 平板、抗旋、健腹轮及体操静力动作主要考验躯干抗伸展/抗旋转能力。
  const isStability = name.includes('plank') || name.includes('pallof') || name.includes('rollerout')
    || name.includes('wheel rollerout') || name.includes('abdominal fallout') || name.includes('body saw')
    || name.includes('dead bug') || name.includes('inchworm') || name.includes('shoulder tap')
    || name.includes('front lever') || name.includes('planche') || name.includes('maltese')
    || name === 'flag' || name.includes('l-sit') || name.includes('v-sit')

  if (isStability) return isOblique ? ['腹斜肌', '核心稳定'] : ['上腹', '核心稳定']

  // 举腿、举膝、反向卷腹和骨盆后倾轨迹统一标记为下腹侧重；带旋转时补充腹斜肌。
  const isLower = name.includes('leg raise') || name.includes('knee raise') || name.includes('reverse crunch')
    || name.includes('hip raise') || name.includes('butt-ups') || name.includes('bottoms-up')
    || name.includes('leg pull') || name.includes('pull-in') || name.includes('pelvic tilt')
    || name.includes('mountain climber') || name.includes('hanging pike')
  if (isLower) return isOblique ? ['下腹', '腹斜肌'] : ['下腹']

  // 旋转、侧屈和对侧屈曲动作以腹斜肌为主；动态全身旋转同时保留核心稳定标签。
  if (isOblique) {
    const dynamicStability = name.includes('slam') || name.includes('sledge') || name.includes('lift')
      || name.includes('lunge') || name.includes('kettlebell') || name.includes('landmine')
    return dynamicStability ? ['腹斜肌', '核心稳定'] : ['腹斜肌']
  }

  // 常规卷腹、仰卧起坐、V 字起身及其余躯干屈曲动作归为上腹侧重。
  return ['上腹']
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'waist')
const classified = exercises.map(exercise => ({ exercise, regions: classifyWaistRegions(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length > 0).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

// 显式记录来源动作 ID，保证迁移不受数据集行序变化影响。
const migration = `-- Waist-region classification generated by scripts/classify-waist-regions.mjs.
-- Upper/lower abs are training-emphasis labels, not separate anatomical muscles.

ALTER TABLE exercise
    ADD COLUMN waist_regions JSON NULL AFTER thigh_regions;

UPDATE exercise
SET waist_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'waist';
`

fs.writeFileSync(migrationFile, migration)
console.log(`腰腹动作：${exercises.length}；已分类：${exercises.length - unknown.length}；待确认：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
