import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const serverRoot = path.resolve(scriptDir, '..')
const datasetFile = path.resolve(serverRoot, '..', 'exercises-dataset-main', 'data', 'exercises.json')
const migrationFile = path.join(serverRoot, 'src', 'main', 'resources', 'db', 'migration', 'V10__add_thigh_regions.sql')

export function classifyThighRegions(exercise) {
  const name = String(exercise.name || '').toLowerCase()

  // 股四头肌目标动作中，深蹲、分腿蹲、弓步和登阶同时显著训练臀肌；孤立伸膝和拉伸仅保留股四头肌。
  if (exercise.target === 'quads') {
    const alsoGlutes = name.includes('squat') || name.includes('lunge') || name.includes('step-up')
      || name.includes('leg press') || name.includes('one leg')
    return alsoGlutes ? ['股四头肌', '臀肌'] : ['股四头肌']
  }

  // 臀肌目标动作按轨迹补充第二标签：膝主导复合动作补股四头肌，髋铰链动作补腘绳肌。
  if (exercise.target === 'glutes') {
    const alsoQuads = name.includes('squat') || name.includes('lunge') || name.includes('step-up')
      || name.includes('leg press') || name.includes('split squat')
    if (alsoQuads) return ['臀肌', '股四头肌']
    const alsoHamstrings = name.includes('deadlift') || name.includes('good morning') || name.includes('pull through')
      || name.includes('hip extension') || name.includes('hip lift') || name.includes('bridge')
      || name.includes('hyperextension') || name.includes('stiff leg')
    return alsoHamstrings ? ['臀肌', '腘绳肌'] : ['臀肌']
  }

  // 腘绳肌动作中的髋铰链、臀腿举和力量翻也显著使用臀肌；腿弯举及拉伸保持单标签。
  if (exercise.target === 'hamstrings') {
    const alsoGlutes = name.includes('deadlift') || name.includes('good morning') || name.includes('glute-ham')
      || name.includes('power clean') || name.includes('hang clean') || name.includes('platform slide')
    return alsoGlutes ? ['腘绳肌', '臀肌'] : ['腘绳肌']
  }

  // 内收、外展目标明确，避免因源数据把臀肌列为协同肌而让孤立动作污染臀肌筛选结果。
  if (exercise.target === 'adductors') return ['内收肌']
  if (exercise.target === 'abductors') return ['外展肌']
  return []
}

const exercises = JSON.parse(fs.readFileSync(datasetFile, 'utf8')).filter(item => item.category === 'upper legs')
const classified = exercises.map(exercise => ({ exercise, regions: classifyThighRegions(exercise) }))
const unknown = classified.filter(item => item.regions.length === 0)
const cases = classified.filter(item => item.regions.length > 0).map(({ exercise, regions }) => {
  const json = JSON.stringify(regions).replaceAll("'", "''")
  return `    WHEN '${exercise.id}' THEN '${json}'`
}).join('\n')

// 显式写入来源动作 ID，使迁移结果不依赖数据集行序。
const migration = `-- Thigh-region classification generated by scripts/classify-thigh-regions.mjs.
-- Primary category remains upper legs; each exercise receives one or two Chinese secondary regions.

ALTER TABLE exercise
    ADD COLUMN thigh_regions JSON NULL AFTER shoulder_regions;

UPDATE exercise
SET thigh_regions = CAST(CASE source_exercise_id
${cases}
    ELSE NULL
END AS JSON)
WHERE source = 'exercise-dataset'
  AND category_code = 'upper legs';
`

fs.writeFileSync(migrationFile, migration)
console.log(`大腿动作：${exercises.length}；已分类：${exercises.length - unknown.length}；待确认：${unknown.length}`)
unknown.forEach(({ exercise }) => console.log(`${exercise.id}\t${exercise.name}\t${exercise.target}`))
